def or_line(row: pd.Series) -> str:
    label = LABELS.get(row["feature"], row["feature"])
    effect = "lower" if row["odds_ratio"] < 1 else "higher"
    pct = abs(row["odds_ratio"] - 1) * 100
    sig = "significant" if row["p_value"] < 0.05 else "not significant"
    return (f"| {label} | {row['odds_ratio']:.2f} | {row['ci_low']:.2f}–{row['ci_high']:.2f} | "
            f"{pct:.0f}% {effect} odds | {sig} |")


