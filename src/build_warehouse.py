"""Build the warehouse: raw CSVs -> staging (cleaned) -> marts (DuckDB).

Also exports marts to CSV for downstream Python steps, and renders
docs/03-data-quality.md from the actual dq_findings / cleaning_log tables.

Fallback: SQLite, if duckdb cannot be imported (SQL is translated on the fly).
"""
from __future__ import annotations

import argparse
import json
import re
import sqlite3
from pathlib import Path

import pandas as pd

RAW_TABLES = ["products", "customers", "orders", "order_items", "marketing_touches", "support_tickets", "returns"]
STG_TABLES = [f"stg_{t}" for t in RAW_TABLES]
MART_TABLES = ["dim_customer", "fct_orders", "fct_order_items", "mart_customer_orders",
               "mart_cohort_retention", "mart_rfm"]
SQL_FILES = ["sql/10_staging.sql", "sql/15_quality.sql", "sql/20_marts.sql"]


def translate_for_sqlite(sql: str) -> str:
    """Best-effort translation of the DuckDB SQL to SQLite (fallback engine)."""
    sql = re.sub(r"DATE '(\d{4}-\d{2}-\d{2})'", r"'\1'", sql)
    sql = re.sub(r"date_diff\('day',\s*([^,]+),\s*([^)]+)\)", r"CAST(julianday(\2) - julianday(\1) AS INTEGER)", sql)
    sql = re.sub(r"date_diff\('second',\s*([^,]+),\s*([^)]+)\)", r"(julianday(\2) - julianday(\1)) * 86400.0", sql)
    sql = sql.replace("TIMESTAMP)", ")")
    sql = sql.replace("CAST(opened_at AS", "CAST(opened_at AS")
    return sql


class DuckEngine:
    def __init__(self, db_path: Path):
        import duckdb
        self.con = duckdb.connect(str(db_path))
        self.name = "duckdb"

    def load_raw(self, table: str, csv: Path) -> None:
        self.con.execute(f"CREATE OR REPLACE TABLE raw_{table} AS SELECT * FROM read_csv_auto('{csv}', header=true)")

    def run_sql_file(self, path: Path) -> None:
        self.con.execute(path.read_text())

    def query_df(self, sql: str) -> pd.DataFrame:
        return self.con.execute(sql).fetchdf()

    def table_names(self) -> set:
        return {r[0] for r in self.con.execute("SHOW TABLES").fetchall()}

    def close(self):
        self.con.close()


class SqliteEngine:
    def __init__(self, db_path: Path):
        self.con = sqlite3.connect(str(db_path))
        self.name = "sqlite"

    def load_raw(self, table: str, csv: Path) -> None:
        df = pd.read_csv(csv)
        df.to_sql(f"raw_{table}", self.con, if_exists="replace", index=False)

    def run_sql_file(self, path: Path) -> None:
        sql = translate_for_sqlite(path.read_text())
        for stmt in [s.strip() for s in sql.split(";") if s.strip() and not s.strip().startswith("--")]:
            self.con.execute(stmt)
        self.con.commit()

    def query_df(self, sql: str) -> pd.DataFrame:
        return pd.read_sql_query(translate_for_sqlite(sql), self.con)

    def table_names(self) -> set:
        return {r[0] for r in self.con.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall()}

    def close(self):
        self.con.close()


def open_engine(db_path: Path):
    try:
        return DuckEngine(db_path)
    except ImportError:
        print("duckdb unavailable -> falling back to SQLite")
        return SqliteEngine(db_path)


def render_quality_report(engine, raw_counts: dict, stg_counts: dict, out_md: Path) -> None:
    log = engine.query_df("SELECT * FROM cleaning_log ORDER BY step_order")
    findings = engine.query_df("SELECT * FROM dq_findings ORDER BY severity, check_name")
    failed = findings[findings["observed"] != findings["expected"]]
    total_found = int(log["rows_found"].sum())
    raw_total = sum(raw_counts.values())

    lines = [
        "# 03 — Data Quality Report",
        "",
        "> Generated by `src/build_warehouse.py` from the actual `cleaning_log` and `dq_findings` tables.",
        "> Numbers below are produced by the pipeline, never hand-written.",
        "",
        "## Summary",
        "",
        f"- Raw rows loaded across 7 tables: **{raw_total:,}**",
        f"- Data-quality issues found in raw: **{total_found:,} rows affected** "
        f"({total_found / raw_total:.2%} of raw rows)",
        f"- Post-clean validation checks passed: **{(findings['observed'] == findings['expected']).sum()}/{len(findings)}**",
        f"- Engine used: `{engine.name}` | Snapshot date: `2025-12-31`",
        "",
        "## Row counts: raw vs staging",
        "",
        "| Table | Raw rows | Staging rows | Removed |",
        "|---|---:|---:|---:|",
    ]
    for raw_name, stg_name in zip(RAW_TABLES, STG_TABLES):
        r, s = raw_counts[raw_name], stg_counts.get(stg_name, 0)
        lines.append(f"| {raw_name} | {r:,} | {s:,} | {r - s:,} |")
    lines += ["", "## Cleaning log — what was found and what was done", "",
              "| # | Table | Issue found | Rows affected | Action | Rule applied |",
              "|---:|---|---|---:|---|---|"]
    for _, row in log.iterrows():
        lines.append(f"| {row['step_order']} | {row['table_name']} | {row['issue']} | "
                     f"{row['rows_found']:,} | {row['action']} | {row['rule_applied']} |")
    lines += ["", "> `action`: `dropped` = row removed; `fixed` = value corrected; `flagged` = kept for awareness.", "",
              "## Post-clean validation (marts safety net)", "",
              "| Check | Table | Observed | Expected | Status |",
              "|---|---|---:|---:|---|"]
    for _, row in findings.iterrows():
        status = "PASS" if row["observed"] == row["expected"] else "FAIL"
        lines.append(f"| {row['check_name']} | {row['table_name']} | {row['observed']} | {row['expected']} | {status} |")
    lines += ["", f"**Result: {'ALL CHECKS PASSED' if len(failed) == 0 else str(len(failed)) + ' CHECKS FAILED'}.**", ""]
    out_md.write_text("\n".join(lines))
    return {"total_issues_found": total_found, "checks": len(findings), "failed": int(len(failed))}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", type=Path, default=Path("data/raw"))
    ap.add_argument("--db", type=Path, default=Path("outputs/warehouse.duckdb"))
    ap.add_argument("--marts-dir", type=Path, default=Path("outputs/marts"))
    ap.add_argument("--report", type=Path, default=Path("docs/03-data-quality.md"))
    args = ap.parse_args()

    args.db.parent.mkdir(parents=True, exist_ok=True)
    if args.db.exists():
        args.db.unlink()
    engine = open_engine(args.db)
    print(f"engine: {engine.name}")

    raw_counts = {}
    for table in RAW_TABLES:
        engine.load_raw(table, args.raw_dir / f"{table}.csv")
        raw_counts[table] = int(engine.query_df(f"SELECT COUNT(*) AS n FROM raw_{table}")["n"][0])
    print("raw loaded:", raw_counts)

    for sql_file in SQL_FILES:
        engine.run_sql_file(Path(sql_file))
        print(f"ran {sql_file}")

    stg_counts = {t: int(engine.query_df(f"SELECT COUNT(*) AS n FROM {t}")["n"][0]) for t in STG_TABLES}
    print("staging:", stg_counts)

    args.marts_dir.mkdir(parents=True, exist_ok=True)
    for table in MART_TABLES:
        engine.query_df(f"SELECT * FROM {table}").to_csv(args.marts_dir / f"{table}.csv", index=False)

    Path("outputs/quality").mkdir(parents=True, exist_ok=True)
    engine.query_df("SELECT * FROM cleaning_log ORDER BY step_order").to_csv("outputs/quality/cleaning_log.csv", index=False)
    engine.query_df("SELECT * FROM dq_findings ORDER BY check_name").to_csv("outputs/quality/dq_findings.csv", index=False)
    result = render_quality_report(engine, raw_counts, stg_counts, args.report)
    Path("outputs/quality/row_counts.json").write_text(json.dumps(
        {"raw": raw_counts, "staging": stg_counts, "engine": engine.name}, indent=2))

    print("marts exported:", MART_TABLES)
    print("quality report:", result)
    engine.close()


if __name__ == "__main__":
    main()
